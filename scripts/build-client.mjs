// Builds client.js from shared/schema.js + src-client/styles.js + src-client/index.js
// wrapped in window.__ModuleLoader__.load(...) with zero ESM export statements.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, '..')

const stripExports = src => src
  .replace(/^export\s+function\s+/gm, 'function ')
  .replace(/^export\s+const\s+/gm, 'const ')

const schemaSrc = stripExports(fs.readFileSync(path.join(rootDir, 'shared', 'schema.js'), 'utf8'))
const stylesSrc = stripExports(fs.readFileSync(path.join(rootDir, 'src-client', 'styles.js'), 'utf8'))
const clientSrc = fs.readFileSync(path.join(rootDir, 'src-client', 'index.js'), 'utf8')

const banner = [
  '// @oxmumu3/dsh-incidental-learn — Browser client bundle (generated by scripts/build-client.mjs).',
  '// Wrapped in window.__ModuleLoader__.load; zero ESM export statements.',
  '',
  'window.__ModuleLoader__.load({',
  "  id: '@oxmumu3/dsh-incidental-learn',",
  '  factory: (require) => {',
  "    'use strict'",
  '    var module = { exports: {} }',
  '    var exports = module.exports',
  '',
].join('\n')

const footer = [
  '',
  '    return module.exports',
  '  },',
  '})',
  '',
].join('\n')

const output = `${banner}${schemaSrc}\n${stylesSrc}\n${clientSrc}${footer}`

if (/^\s*export\s+/m.test(output)) {
  throw new Error('client.js still contains ESM export statement!')
}

fs.writeFileSync(path.join(rootDir, 'client.js'), output, 'utf8')
console.log(`Built client.js (${Buffer.byteLength(output, 'utf8')} bytes)`)
